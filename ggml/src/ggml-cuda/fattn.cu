// Best FlashAttention kernel for a specific GPU:
enum best_fattn_kernel {
    BEST_FATTN_KERNEL_NONE     =   0,
    BEST_FATTN_KERNEL_TILE     = 200,
    BEST_FATTN_KERNEL_VEC      = 100,
    BEST_FATTN_KERNEL_WMMA_F16 = 300,
    BEST_FATTN_KERNEL_MMA_F16  = 400,
};

static bool ggml_cuda_fattn_kv_type_supported(ggml_type type) {
    switch (type) {
        case GGML_TYPE_F32:
        case GGML_TYPE_F16:
            return true;
        case GGML_TYPE_Q4_1:
        case GGML_TYPE_Q5_0:
        case GGML_TYPE_Q5_1:
#ifndef GGML_CUDA_FA_ALL_QUANTS
            return false;
#endif // GGML_CUDA_FA_ALL_QUANTS
        case GGML_TYPE_Q4_0:
        case GGML_TYPE_Q8_0:
        case GGML_TYPE_BF16:
            return true;
        default:
            return false;
    }
}

static best_fattn_kernel ggml_cuda_get_best_fattn_kernel(const int device, const ggml_tensor * dst) {
#ifndef FLASH_ATTN_AVAILABLE
    GGML_UNUSED(device); GGML_UNUSED(dst);
    return BEST_FATTN_KERNEL_NONE;
#endif// FLASH_ATTN_AVAILABLE

    const ggml_tensor * KQV   = dst;
    const ggml_tensor * Q     = dst->src[0];
    const ggml_tensor * K     = dst->src[1];
    const ggml_tensor * V     = dst->src[2];
    const ggml_tensor * mask  = dst->src[3];

    const int gqa_ratio = Q->ne[2] / K->ne[2];
    GGML_ASSERT(Q->ne[2] % K->ne[2] == 0);

    float max_bias = 0.0f;
    memcpy(&max_bias, (const float *) KQV->op_params + 1, sizeof(float));

    // The effective batch size for the kernel can be increased by gqa_ratio.
    // The kernel versions without this optimization are also used for ALiBi, if there is no mask, or if the KV cache is not padded,
    bool gqa_opt_applies = gqa_ratio >= 2 && mask && max_bias == 0.0f && K->ne[1] % FATTN_KQ_STRIDE == 0;
    for (const ggml_tensor * t : {Q, K, V, mask}) {
        if (t == nullptr || ggml_is_quantized(t->type)) {
            continue;
        }
        for (size_t i = 1; i < GGML_MAX_DIMS; ++i) {
            if (t->nb[i] % 16 != 0) {
                gqa_opt_applies = false;
                break;
            }
        }
    }

    const int cc = ggml_cuda_info().devices[device].cc;

    switch (K->ne[0]) {
        case  40:
        case  64:
        case  72:
        case  80:
        case  96:
        case 128:
        case 112:
        case 256:
            if (V->ne[0] != K->ne[0]) {
                return BEST_FATTN_KERNEL_NONE;
            }
            break;
        case 192:
            if (V->ne[0] != 128 || !gqa_opt_applies) {
                return BEST_FATTN_KERNEL_NONE;
            }
            if (gqa_ratio % 8 != 0) {
                return BEST_FATTN_KERNEL_NONE;
            }
            break;
        case 320:
            if (V->ne[0] != 256 || !gqa_opt_applies) {
                return BEST_FATTN_KERNEL_NONE;
            }
            if (gqa_ratio % 32 != 0) {
                return BEST_FATTN_KERNEL_NONE;
            }
            break;
        case 512:
            if (V->ne[0] != K->ne[0]) {
                return BEST_FATTN_KERNEL_NONE;
            }
            if (!gqa_opt_applies) {
                return BEST_FATTN_KERNEL_NONE;
            }
            break;
        case 576:
            if (V->ne[0] != 512) {
                return BEST_FATTN_KERNEL_NONE;
            }
            if (!gqa_opt_applies) {
                return BEST_FATTN_KERNEL_NONE;
            }
            break;
        default:
            return BEST_FATTN_KERNEL_NONE;
    }

#ifndef GGML_CUDA_FA_ALL_QUANTS
    if (K->type != V->type) {
        return BEST_FATTN_KERNEL_NONE;
    }
#endif // GGML_CUDA_FA_ALL_QUANTS

    if (!ggml_cuda_fattn_kv_type_supported(K->type) || !ggml_cuda_fattn_kv_type_supported(V->type)) {
        return BEST_FATTN_KERNEL_NONE;
    }

    if (mask && mask->ne[2] != 1) {
        return BEST_FATTN_KERNEL_NONE;
    }

    // For small batch sizes the vector kernel may be preferable over the kernels optimized for large batch sizes:
    // 192 satisfies % 64 == 0 but has no vec instance (DKQ != DV); force it onto the MMA path.
    const bool can_use_vector_kernel = Q->ne[0] <= 256 && Q->ne[0] % 64 == 0 && Q->ne[0] != 192 && K->ne[1] % FATTN_KQ_STRIDE == 0;

    // If Turing tensor cores are available, use them:
    if (turing_mma_available(cc) && Q->ne[0] != 40 && Q->ne[0] != 72) {
        if (can_use_vector_kernel) {
            if (!ggml_is_quantized(K->type) && !ggml_is_quantized(V->type)) {
                if (cc >= GGML_CUDA_CC_ADA_LOVELACE && Q->ne[1] == 1 && Q->ne[3] == 1 && !(gqa_ratio > 4 && K->ne[1] >= 8192)) {
                    return BEST_FATTN_KERNEL_VEC;
                }
            } else {
                if (cc >= GGML_CUDA_CC_ADA_LOVELACE) {
                    if (Q->ne[1] <= 2) {
                        return BEST_FATTN_KERNEL_VEC;
                    }
                } else {
                    if (Q->ne[1] == 1) {
                        return BEST_FATTN_KERNEL_VEC;
                    }
                }
            }
            if (!gqa_opt_applies && Q->ne[1] == 1) {
                return BEST_FATTN_KERNEL_VEC;
            }
        }
        return BEST_FATTN_KERNEL_MMA_F16;
    }

    const int ncols2_max = Q->ne[0] == 320 ? 32 : ((Q->ne[0] == 576 || Q->ne[0] == 192) ? 16 : 8);
    int gqa_ratio_eff = 1;
    while (gqa_ratio % (2*gqa_ratio_eff) == 0 && gqa_ratio_eff < ncols2_max) {
        gqa_ratio_eff *= 2;
    }

    if (volta_mma_available(cc) && Q->ne[0] != 40 && Q->ne[0] != 72) {
        if (can_use_vector_kernel && Q->ne[1] * gqa_ratio_eff <= 2) {
            return BEST_FATTN_KERNEL_VEC;
        }
        if (Q->ne[1] * gqa_ratio_eff <= 16) {
            return BEST_FATTN_KERNEL_TILE; // On Volta tensor cores are only faster for sufficiently large matrices.
        }
        return BEST_FATTN_KERNEL_MMA_F16;
    }

    // Use the WMMA kernel if possible:
    if (ggml_cuda_should_use_wmma_fattn(cc) && K->ne[1] % FATTN_KQ_STRIDE == 0 && Q->ne[0] != 40 && Q->ne[0] != 72 && Q->ne[0] != 192 && Q->ne[0] != 512 && Q->ne[0] != 576) {
        if (can_use_vector_kernel && Q->ne[1] <= 2) {
            return BEST_FATTN_KERNEL_VEC;
        }
        return BEST_FATTN_KERNEL_WMMA_F16;
    }

    // AMD MFMA needs a certain minimum batch size to outscale the tile kernel for large head sizes.
    if ((amd_mfma_available(cc) && Q->ne[0] <= 256) && Q->ne[0] != 40 && Q->ne[0] != 72) {
        if ((Q->ne[0] <= 64 && Q->ne[1] * gqa_ratio_eff > 8)) {
            return BEST_FATTN_KERNEL_MMA_F16;
        }
        if ((Q->ne[0] <= 128 && Q->ne[1] * gqa_ratio_eff > 16)) {
            return BEST_FATTN_KERNEL_MMA_F16;
        }
        if ((Q->ne[0] <= 256 && Q->ne[1] * gqa_ratio_eff > 64)) {
            return BEST_FATTN_KERNEL_MMA_F16;
        }
    }

    // AMD WMMA is always faster than the tile kernel if the full tile width of 16 can be utilized.
    if ((amd_wmma_available(cc) && gqa_opt_applies && Q->ne[0] <= 128) && Q->ne[0] != 40 && Q->ne[0] != 72 && Q->ne[1] * gqa_ratio_eff > 8) {
        return BEST_FATTN_KERNEL_MMA_F16;
    }

    // If there are no tensor cores available, use the generic tile kernel:
    if (can_use_vector_kernel) {
        if (!ggml_is_quantized(K->type) && !ggml_is_quantized(V->type)) {
            if (Q->ne[1] == 1) {
                if (!gqa_opt_applies) {
                    return BEST_FATTN_KERNEL_VEC;
                }
            }
        } else {
            if (Q->ne[1] <= 2) {
                return BEST_FATTN_KERNEL_VEC;
            }
        }
    }
    return BEST_FATTN_KERNEL_TILE;
}

size_t ggml_cuda_flash_attn_ext_get_alloc_size(int device, const ggml_tensor * dst) {
    GGML_ASSERT(dst->op == GGML_OP_FLASH_ATTN_EXT || dst->op == GGML_OP_FLASH_ATTN_PARTIAL);

    const ggml_tensor * K = dst->src[1];
    const ggml_tensor * V = dst->src[2];

    GGML_ASSERT(K != nullptr);
    GGML_ASSERT(V != nullptr);

    // partial attention launches the tile or mma family (see
    // ggml_cuda_flash_attn_partial); both need F16 K/V scratch
    const best_fattn_kernel kernel = dst->op == GGML_OP_FLASH_ATTN_PARTIAL
        ? BEST_FATTN_KERNEL_TILE
        : ggml_cuda_get_best_fattn_kernel(device, dst);

    bool need_f16_K = false;
    bool need_f16_V = false;

    switch (kernel) {
        case BEST_FATTN_KERNEL_TILE:
        case BEST_FATTN_KERNEL_WMMA_F16:
        case BEST_FATTN_KERNEL_MMA_F16:
            need_f16_K = true;
            need_f16_V = true;
            break;
        case BEST_FATTN_KERNEL_VEC:
            need_f16_K = K->type == GGML_TYPE_F32;
            need_f16_V = V->type == GGML_TYPE_F32;
            break;
        case BEST_FATTN_KERNEL_NONE:
            break;
    }

    const ggml_cuda_flash_attn_ext_f16_extra_data f16_extra =
        ggml_cuda_flash_attn_ext_get_f16_extra_data(dst, need_f16_K, need_f16_V);

    return f16_extra.end - (uintptr_t) dst->data;
}

void ggml_cuda_flash_attn_ext(ggml_backend_cuda_context & ctx, ggml_tensor * dst) {
    ggml_cuda_set_device(ctx.device);
    switch (ggml_cuda_get_best_fattn_kernel(ggml_cuda_get_device(), dst)) {
        case BEST_FATTN_KERNEL_NONE:
            GGML_ABORT("fatal error");
        case BEST_FATTN_KERNEL_TILE:
            ggml_cuda_flash_attn_ext_tile(ctx, dst);
            break;
        case BEST_FATTN_KERNEL_VEC:
            ggml_cuda_flash_attn_ext_vec(ctx, dst);
            break;
        case BEST_FATTN_KERNEL_WMMA_F16:
            ggml_cuda_flash_attn_ext_wmma_f16(ctx, dst);
            break;
        case BEST_FATTN_KERNEL_MMA_F16:
            ggml_cuda_flash_attn_ext_mma_f16(ctx, dst);
            break;
    }
}

bool ggml_cuda_flash_attn_ext_supported(int device, const ggml_tensor * dst) {
    return ggml_cuda_get_best_fattn_kernel(device, dst) != BEST_FATTN_KERNEL_NONE;
}

// S2b pair-sharded decode: partial attention (see GGML_OP_FLASH_ATTN_PARTIAL).
// Kernels are the unchanged tile family; launch_fattn detects the op on dst
// and swaps the epilogue for flash_attn_combine_to_partial.
void ggml_cuda_flash_attn_partial(ggml_backend_cuda_context & ctx, ggml_tensor * dst) {
    GGML_ASSERT(dst->op == GGML_OP_FLASH_ATTN_PARTIAL);
    GGML_ASSERT(dst->src[4] == nullptr && "sinks unsupported in partial attention");
    // S2b-at-prefill member beyond the sequential cache fill: no K rows on
    // this member. The dst slots still get exchanged, so emit the neutral
    // partial explicitly: all-zero rows have S == 0, which the combiner
    // treats as an inert slot. The kernel path cannot run with 0 KV tiles.
    if (dst->src[1]->ne[1] == 0) {
        CUDA_CHECK(cudaMemsetAsync(dst->data, 0, ggml_nbytes(dst), ctx.stream()));
        return;
    }
    // One-launch S2b audit: inspect the exact per-member mask presented to
    // layer 0 before the partial kernel. This is deliberately device-scoped
    // so a single model launch diagnoses both members of every TP pair.
    static const bool s2b_audit = getenv("LLAMA_S2B_AUDIT") != nullptr;
    const ggml_tensor * mask = dst->src[3];
    if (s2b_audit && mask != nullptr && strcmp(dst->name, "s2b_partial-0") == 0) {
        static std::atomic<uint32_t> audited_devices{0};
        const int dev = ctx.device;
        const uint32_t bit = dev >= 0 && dev < 32 ? 1u << dev : 0;
        cudaStreamCaptureStatus capture = cudaStreamCaptureStatusNone;
        if (bit != 0 && cudaStreamIsCapturing(ctx.stream(), &capture) == cudaSuccess &&
                capture == cudaStreamCaptureStatusNone &&
                (audited_devices.fetch_or(bit) & bit) == 0) {
            GGML_ASSERT(mask->type == GGML_TYPE_F16);
            const size_t n = ggml_nelements(mask);
            std::vector<uint16_t> h(n);
            CUDA_CHECK(cudaMemcpyAsync(h.data(), mask->data, n*sizeof(uint16_t),
                    cudaMemcpyDeviceToHost, ctx.stream()));
            CUDA_CHECK(cudaStreamSynchronize(ctx.stream()));
            size_t zeros = 0, neg_inf = 0, other = 0;
            for (uint16_t x : h) {
                if (x == 0x0000) {
                    zeros++;
                } else if (x == 0xfc00) {
                    neg_inf++;
                } else {
                    other++;
                }
            }
            fprintf(stderr,
                    "[S2BAUDIT-MASK] dev=%d name=%s ne=[%lld,%lld,%lld,%lld] zero=%zu -inf=%zu other=%zu first16=",
                    dev, mask->name,
                    (long long) mask->ne[0], (long long) mask->ne[1],
                    (long long) mask->ne[2], (long long) mask->ne[3],
                    zeros, neg_inf, other);
            for (size_t i = 0; i < std::min<size_t>(16, h.size()); ++i) {
                fprintf(stderr, "%c", h[i] == 0 ? 'U' : h[i] == 0xfc00 ? '.' : '?');
            }
            fprintf(stderr, "\n");
            fflush(stderr);
        }
    }
    // Prefill-shaped partials (S2b-at-prefill: wide Q over the member's cache
    // slice) ride the mma family via forced tile splitting in launch_fattn;
    // K->ne[1] >= 2*FATTN_KQ_STRIDE guarantees the >= 2 KV chunks per tile
    // that splitting needs. Decode partials (T <= 8, gathered F16 K) and
    // batched verify partials (ne[3] > 1) stay on the tile family.
    const ggml_tensor * Q = dst->src[0];
    if (Q->ne[1] >= 32 && Q->ne[3] == 1 && dst->src[1]->ne[1] >= 2*FATTN_KQ_STRIDE &&
            ggml_cuda_get_best_fattn_kernel(ggml_cuda_get_device(), dst) == BEST_FATTN_KERNEL_MMA_F16) {
        ggml_cuda_flash_attn_ext_mma_f16(ctx, dst);
        return;
    }
    ggml_cuda_flash_attn_ext_tile(ctx, dst);
}

// Merge the member slots of a completed FLASH_ATTN_PARTIAL allreduce:
// dst[row] = sum_s e^{Ms-M} num_s / sum_s e^{Ms-M} S_s  over valid slots.
// Scale-invariant per slot, so an all-zero (empty-member) slot is naturally
// inert through the S>0 guards.
#define GGML_CUDA_FA_COMBINE_MAX_SLOTS 16
static __global__ void k_flash_attn_combine(
        const float * part, float * dst, const int64_t D, const int64_t nrows, const int n_slots) {
    const int64_t row = blockIdx.x;
    if (row >= nrows) {
        return;
    }
    // S == 0 is the neutral/empty partial. Its stored M is only a finite
    // placeholder and must not participate in the maximum; otherwise an
    // empty member with M=0 can suppress a valid member whose maximum is
    // sufficiently negative (and expf(Mvalid - 0) can underflow).
    const float * slot[GGML_CUDA_FA_COMBINE_MAX_SLOTS];
    bool  valid[GGML_CUDA_FA_COMBINE_MAX_SLOTS];
    float M = -INFINITY;
    for (int s = 0; s < n_slots; ++s) {
        slot[s] = part + ((int64_t) s*nrows + row)*(D + 2);
        const float Ms = slot[s][D], Ss = slot[s][D + 1];
        valid[s] = isfinite(Ss) && Ss > 0.0f && isfinite(Ms);
        if (valid[s]) {
            M = fmaxf(M, Ms);
        }
    }
    float e[GGML_CUDA_FA_COMBINE_MAX_SLOTS];
    float S = 0.0f;
    for (int s = 0; s < n_slots; ++s) {
        e[s] = valid[s] ? expf(slot[s][D] - M) : 0.0f;
        S   += e[s]*slot[s][D + 1];
    }
    const float inv_S = S > 0.0f ? 1.0f/S : 0.0f;
    for (int64_t d = threadIdx.x; d < D; d += blockDim.x) {
        float acc = 0.0f;
        for (int s = 0; s < n_slots; ++s) {
            // Do not evaluate 0*NaN for an empty member partial.
            acc += valid[s] ? e[s]*slot[s][d] : 0.0f;
        }
        dst[row*D + d] = acc * inv_S;
    }
}

void ggml_cuda_flash_attn_combine(ggml_backend_cuda_context & ctx, ggml_tensor * dst) {
    const ggml_tensor * part = dst->src[0];
    GGML_ASSERT(part->type == GGML_TYPE_F32 && dst->type == GGML_TYPE_F32);
    GGML_ASSERT(part->ne[3] >= 2 && part->ne[3] <= GGML_CUDA_FA_COMBINE_MAX_SLOTS);
    GGML_ASSERT(ggml_is_contiguous(part) && ggml_is_contiguous(dst));
    const int64_t D       = dst->ne[0];
    const int64_t nrows   = dst->ne[1]*dst->ne[2];
    const int     n_slots = (int) part->ne[3];
    GGML_ASSERT(part->ne[0] == D + 2);

    static const bool s2b_audit = getenv("LLAMA_S2B_AUDIT") != nullptr;
    if (s2b_audit && strcmp(part->name, "s2b_partial-0") == 0) {
        static std::atomic<uint32_t> audited_devices{0};
        const int dev = ctx.device;
        const uint32_t bit = dev >= 0 && dev < 32 ? 1u << dev : 0;
        cudaStreamCaptureStatus capture = cudaStreamCaptureStatusNone;
        if (bit != 0 && cudaStreamIsCapturing(ctx.stream(), &capture) == cudaSuccess &&
                capture == cudaStreamCaptureStatusNone &&
                (audited_devices.fetch_or(bit) & bit) == 0) {
            const int64_t sample_rows = std::min<int64_t>(nrows, 4);
            std::vector<float> h((size_t) ggml_nelements(part));
            CUDA_CHECK(cudaMemcpyAsync(h.data(), part->data, h.size()*sizeof(float),
                    cudaMemcpyDeviceToHost, ctx.stream()));
            CUDA_CHECK(cudaStreamSynchronize(ctx.stream()));
            fprintf(stderr, "[S2BAUDIT-PARTIAL] dev=%d D=%lld nrows=%lld",
                    dev, (long long) D, (long long) nrows);
            for (int64_t r = 0; r < sample_rows; ++r) {
                const size_t oa = (size_t) r*(D + 2);
                const size_t ob = (size_t) nrows*(D + 2) + oa;
                fprintf(stderr, " r%lld={A:M%.6g,S%.6g,n0%.6g B:M%.6g,S%.6g,n0%.6g}",
                        (long long) r, h[oa + D], h[oa + D + 1], h[oa],
                        h[ob + D], h[ob + D + 1], h[ob]);
            }
            fprintf(stderr, "\n");
            fflush(stderr);
        }
    }

    // LLAMA_S2B_AUDIT2: all-slot M/S dump + full-buffer hash of the completed
    // (post-exchange) partial. First 8 launches per device.
    static const bool s2b_audit2 = getenv("LLAMA_S2B_AUDIT2") != nullptr;
    if (s2b_audit2 && strncmp(part->name, "s2b_partial-", 12) == 0) {
        static std::atomic<int> a2_count[GGML_CUDA_MAX_DEVICES];
        const int dev = ctx.device;
        cudaStreamCaptureStatus capture = cudaStreamCaptureStatusNone;
        if (dev >= 0 && dev < GGML_CUDA_MAX_DEVICES &&
                cudaStreamIsCapturing(ctx.stream(), &capture) == cudaSuccess &&
                capture == cudaStreamCaptureStatusNone &&
                a2_count[dev].fetch_add(1) < 8) {
            std::vector<float> h((size_t) ggml_nelements(part));
            CUDA_CHECK(cudaMemcpyAsync(h.data(), part->data, h.size()*sizeof(float),
                    cudaMemcpyDeviceToHost, ctx.stream()));
            CUDA_CHECK(cudaStreamSynchronize(ctx.stream()));
            uint64_t fnv = 1469598103934665603ULL;
            const uint8_t * hb = (const uint8_t *) h.data();
            for (size_t i = 0; i < h.size()*sizeof(float); ++i) {
                fnv = (fnv ^ hb[i]) * 1099511628211ULL;
            }
            fprintf(stderr, "[S2BAUDIT2-COMBINE] dev=%d name=%s D=%lld nrows=%lld nslots=%d hash=%016llx",
                    dev, part->name, (long long) D, (long long) nrows, n_slots,
                    (unsigned long long) fnv);
            for (int64_t r = 0; r < std::min<int64_t>(nrows, 2); ++r) {
                fprintf(stderr, " r%lld=[", (long long) r);
                for (int s = 0; s < n_slots; ++s) {
                    const size_t o = ((size_t) s*nrows + r)*(D + 2);
                    fprintf(stderr, "%sM%.6g,S%.6g,n0%.6g", s ? " | " : "",
                            h[o + D], h[o + D + 1], h[o]);
                }
                fprintf(stderr, "]");
            }
            fprintf(stderr, "\n");
            fflush(stderr);
        }
    }

    const dim3 grid((unsigned) nrows, 1, 1);
    const dim3 block(256, 1, 1);
    const ggml_cuda_kernel_launch_params lp = ggml_cuda_kernel_launch_params(grid, block, 0, ctx.stream());
    ggml_cuda_kernel_launch(k_flash_attn_combine, lp,
        (const float *) part->data, (float *) dst->data, D, nrows, n_slots);
    CUDA_CHECK(cudaGetLastError());
}
